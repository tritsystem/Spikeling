#!/usr/bin/env python3
"""Stage 2 of device-idea #17's build plan: export the EXACT M=128, seed=0
clean-case reservoir (bonds, input weights, drive/target sequences, and the
trained ridge decoder) that fib_noise_combined_check_M128.py already measured
at NMSE=0.4464, as C constant arrays -- so the real CCodeGenerator + the real
spikeling_resonator_step() C function can be cross-checked against this exact
number instead of a re-derived one.

Reuses fib_K / ridge / nmse / run / make_XY VERBATIM from
fib_noise_combined_check_M128.py (import by path, no re-derivation).
"""
import os, sys, importlib.util
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "core"))

spec = importlib.util.spec_from_file_location("fib_m128", os.path.join(HERE, "fib_noise_combined_check_M128.py"))
fib_m128 = importlib.util.module_from_spec(spec)
sys.argv = [sys.argv[0]]  # the module runs its test at import time; harmless, just prints again
spec.loader.exec_module(fib_m128)

M, SEED = 128, 0
K = fib_m128.fib_K(M)
Xf, yb = fib_m128.make_XY(K, SEED)          # verbatim call, identical to the measured run
tr = int(0.6 * len(yb))
weights = fib_m128.ridge(Xf[:tr], yb[:tr])   # the exact trained decoder for this seed
nmse_check = fib_m128.nmse(Xf[tr:] @ weights, yb[tr:])
print(f"\n[export] re-derived clean NMSE for seed {SEED} (sanity check, must match the logged 0.4464): {nmse_check:.4f}")

# Reconstruct u exactly as make_XY did (same rng draw order: u then win)
rng = np.random.default_rng(SEED)
u_full = rng.standard_normal(fib_m128.T)
win = rng.uniform(-1, 1, M)

bonds = np.array([K[i, i + 1] for i in range(M - 1)])  # already RHO-normalized, ready to use as-is

def c_array(name, arr, dtype="float"):
    vals = ", ".join(f"{v:.10f}f" for v in np.asarray(arr).ravel())
    return f"static const {dtype} {name}[{len(np.asarray(arr).ravel())}] = {{{vals}}};"

# Isolated subdirectory -- NOT core/examples/ directly, which holds shared
# auto-generated spikeling_hw.c/.h for OTHER examples (test_tone_detector.c);
# writing there once clobbered that tracked file until git checkout restored it.
out_path = os.path.normpath(os.path.join(HERE, "..", "core", "examples", "fib_reservoir_M128_build", "fib_reservoir_data.h"))
os.makedirs(os.path.dirname(out_path), exist_ok=True)

with open(out_path, "w", encoding="utf-8") as f:
    f.write("/* Auto-generated by export_fib_reservoir_c.py -- DO NOT EDIT.\n")
    f.write(f" * M={M} Fibonacci-coupled Resonator chain, seed={SEED}, clean (no added noise).\n")
    f.write(f" * Python re-derived NMSE for this exact config: {nmse_check:.4f}\n")
    f.write(f" * (measured/logged value from fib_noise_combined_check_M128.py: 0.4464)\n")
    f.write(" * Cross-backend target: the C reservoir_driver.c should reproduce this NMSE. */\n")
    f.write("#ifndef FIB_RESERVOIR_DATA_H\n#define FIB_RESERVOIR_DATA_H\n\n")
    f.write(f"#define FIB_M {M}\n")
    f.write(f"#define FIB_T {fib_m128.T}\n")
    f.write(f"#define FIB_BURN {fib_m128.BURN}\n")
    f.write(f"#define FIB_HOLD {fib_m128.HOLD}\n")
    f.write(f"#define FIB_DT {fib_m128.DT}f\n")
    f.write(f"#define FIB_TR {tr}\n")
    f.write(f"#define FIB_PY_NMSE {nmse_check:.10f}f\n\n")
    f.write(c_array("fib_bonds", bonds) + "\n\n")
    f.write(c_array("fib_win", win) + "\n\n")
    f.write(c_array("fib_u", u_full) + "\n\n")
    f.write(c_array("fib_y_burned", yb) + "\n\n")
    f.write(c_array("fib_decoder_weights", weights) + "\n\n")
    f.write("#endif /* FIB_RESERVOIR_DATA_H */\n")

print(f"[export] wrote {out_path}")
print(f"[export] M={M} bonds={len(bonds)} win={len(win)} u={len(u_full)} y_burned={len(yb)} weights={len(weights)}")
