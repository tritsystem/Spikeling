#!/usr/bin/env python
"""
animal_gate_spk_builder.py
===========================
Generates the animal-call-discrimination .spk network FROM
animal_acoustic_config.py's data-driven CLASSES / ENV_GATE_RULES lists,
instead of hand-writing Resonator neuron lines per species in the .spk
file itself. Adding a new animal class is a config-file change; this
script (and the resulting .spk text) never needs touching for that.

Emits, per animal_acoustic_config.CLASSES entry:
  - one `neuron ... type=Resonator freq=... damping=...` line per
    ResonatorBand (name = f"{class.label}_{band.band_label}", or just
    `class.label` when the class has exactly one band)
  - one `action <neuron> -> [DETECT_<NAME>]` line per band

Plus, ONCE (not per-class -- these are shared environmental-plausibility
signals the driver applies to whichever class needs them, per
EnvGateRule.applies_to):
  - one LIF `Gate<rule.label>` neuron per ENV_GATE_RULES entry
  - one LIF `RegionPrior_<class.label>` neuron per CLASSES entry (the
    real, wired-but-currently-neutral geolocation input channel -- see
    REGION_PRIOR_STUB's docstring in the config)

ARCHITECTURAL CONSTRAINT (real, not a design choice -- see
core/compiler/compiler.py and core/runtime/runtime.py): Resonator neurons
dispatch fired actions through the same action/handler path a LIF neuron
uses, but do NOT participate in `connect`-based synapse propagation (the
C-codegen path explicitly splits `lif_neurons` from `resonator_neurons`,
and step_resonators() never calls the only code path that walks
synapses). A `connect ResonatorX -> LIFY` line would parse but silently do
nothing at runtime, so none is emitted here. Acoustic + environmental
composition happens in the driver (animal_species_classifier.py), via
handlers registered on both populations of the SAME SpikelingRuntime --
still one shared network, just cross-population logic lives in Python
instead of a `connect` statement this runtime doesn't support here.

Run directly to (re)generate animal_detector_gate.spk from the current
config:
    python animal_gate_spk_builder.py
"""
import os

from animal_acoustic_config import CLASSES, ENV_GATE_RULES

OUTPUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "animal_detector_gate.spk")


def _band_neuron_name(cls, band) -> str:
    return cls.label if len(cls.bands) == 1 else f"{cls.label}_{band.band_label}"


def build_spk_text() -> str:
    lines = []
    lines.append("# animal_detector_gate.spk")
    lines.append("# =====================================================================")
    lines.append("# AUTO-GENERATED by animal_gate_spk_builder.py from animal_acoustic_config.py")
    lines.append("# -- do not hand-edit the neuron/action lines below; edit the config and")
    lines.append("# re-run the builder instead. See that config module's docstring for the")
    lines.append("# real-data discipline (every frequency here is cited, not invented) and")
    lines.append("# animal_species_classifier.py for how acoustic + environmental channels")
    lines.append("# are composed (NOT via `connect` -- see the builder's own module")
    lines.append("# docstring for the real architectural reason why).")
    lines.append("#")
    lines.append("# Config-driven animal-call discrimination prototype (generalized from an")
    lines.append("# original UK-bat-specific version). Populated classes and their citations:")
    for c in CLASSES:
        lines.append(f"#   {c.label} ({'genus/cluster-level' if c.genus_level else 'species-level'}): {c.citation}")
    lines.append("#")
    lines.append("# TESTED ONLY against synthetic tones/chirps (see")
    lines.append("# test_animal_gate_synthetic.py) -- never against a real recording of any")
    lines.append("# of the above. This is a capability-bar test of the Resonator primitive,")
    lines.append("# not a validated classifier for any real animal.")
    lines.append("")

    lines.append("# ---- Acoustic channels (Resonator neurons, config-driven) ----")
    for c in CLASSES:
        for band in c.bands:
            name = _band_neuron_name(c, band)
            lines.append(f"neuron {name} type=Resonator freq={band.freq_hz} damping={band.damping}")
    lines.append("")

    lines.append("# ---- Environmental-plausibility gate channels (plain LIF, rate-coded) ----")
    lines.append("# One shared neuron per EnvGateRule (not per-class) -- driven externally by")
    lines.append("# animal_species_classifier.set_environment() at a rate that reliably")
    lines.append("# crosses threshold when the rule's condition is currently true.")
    for rule in ENV_GATE_RULES:
        lines.append(f"neuron Gate{rule.label} threshold=40 leak=5 type=LIF")
    lines.append("")

    lines.append("# ---- Regional/geolocation prior channels (STUB -- see config's")
    lines.append("# REGION_PRIOR_STUB docstring; every class gets one real, wired input")
    lines.append("# channel here even though the driving value is currently neutral) ----")
    for c in CLASSES:
        lines.append(f"neuron RegionPrior_{c.label} threshold=40 leak=5 type=LIF")
    lines.append("")

    lines.append("# ---- Actions ----")
    for c in CLASSES:
        for band in c.bands:
            name = _band_neuron_name(c, band)
            lines.append(f"action {name} -> [DETECT_{name.upper()}]")
    for rule in ENV_GATE_RULES:
        lines.append(f"action Gate{rule.label} -> [ENV_GATE_{rule.label.upper()}]")
    for c in CLASSES:
        lines.append(f"action RegionPrior_{c.label} -> [ENV_REGION_{c.label.upper()}]")
    lines.append("")
    lines.append("refractory=1ms")
    lines.append("")
    return "\n".join(lines)


def main():
    text = build_spk_text()
    with open(OUTPUT_PATH, "w") as f:
        f.write(text)
    n_resonators = sum(len(c.bands) for c in CLASSES)
    print(f"Wrote {OUTPUT_PATH}")
    print(f"  {len(CLASSES)} acoustic classes, {n_resonators} Resonator neurons, "
          f"{len(ENV_GATE_RULES)} env-gate rules, {len(CLASSES)} region-prior channels")


if __name__ == "__main__":
    main()
