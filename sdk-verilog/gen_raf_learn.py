"""
Generate spikeling_raf_learn.v + tb_raf_learn.v -- the RAF-resonator-bank
ON-CHIP LEARNING RULE as synthesizable fixed-point hardware.

    python gen_raf_learn.py                 # default 4-channel demo
    python gen_raf_learn.py 311 523 881 1483

Emits, for the given per-channel dither frequencies:
  spikeling_raf_learn.v   -- the learner module (resonator bank + DDS dither +
                             velocity-phase sign readout + signSGD update)
  tb_raf_learn.v          -- self-checking testbench: closes the loop with a
                             quadratic loss L = sum_j (param_out_j - target_j)^2
                             and asserts every param_j converges to its target.

Fixed-point identical to spikeling_resonators.v (Q14.18 state, Q28.36/64-bit
energy, dt = 2^-15, alpha decay = >>ALPHA_SHIFT). The bit-accurate Python twin
is spikeling_raf_learn_model.py::RAFLearnCore (mode="SIGN").
"""
import sys
import math
from spikeling_raf_learn_model import (
    FRAC, WIDTH, DT_SHIFT, ENERGY_WIDTH, ALPHA_SHIFT, PHASE_BITS,
    res_consts, q, DT, SINE_LUT,
)

WINDOW = 4000
SETTLE = 2000
LOSS_ALPHA_SHIFT = 7
DRIVE_GAIN_SHIFT = 4
STEP_SHIFT = 10          # signSGD step = 2^-8 in Q14.18 ~= 0.0039 / window
VREF_ACC_W = 48
TARGETS = [0.35, -0.30, 0.20, -0.15]
AMP = 0.05
N_WINDOWS_TB = 200
TOL = 0.05


def hx(v, w):
    return f"{w}'sh{(v & ((1 << w) - 1)):0{(w + 3) // 4}x}"


def gen_module(freqs):
    N = len(freqs)
    K = [res_consts(f) for f in freqs]
    pinc = [int(round(f * DT * (1 << PHASE_BITS))) for f in freqs]
    amp = q(AMP)
    L = []
    P = L.append
    P("// Auto-generated by gen_raf_learn.py -- DO NOT EDIT")
    P("// RAF-resonator-bank on-chip learning rule. Bit-accurate twin:")
    P("// spikeling_raf_learn_model.py::RAFLearnCore(mode=\"SIGN\").")
    P("// Requires iverilog -g2012 (packed-array ports), same as spikeling_resonators.v.")
    P("")
    P(f"module spikeling_raf_learn #(")
    P(f"    parameter WIDTH = {WIDTH},")
    P(f"    parameter FRAC = {FRAC},")
    P(f"    parameter ENERGY_WIDTH = {ENERGY_WIDTH},")
    P(f"    parameter PHASE_BITS = {PHASE_BITS},")
    P(f"    parameter integer N = {N},")
    P(f"    parameter integer WINDOW = {WINDOW},")
    P(f"    parameter integer SETTLE = {SETTLE},")
    P(f"    parameter integer DT_SHIFT = {DT_SHIFT},")
    P(f"    parameter integer ALPHA_SHIFT = {ALPHA_SHIFT},")
    P(f"    parameter integer LOSS_ALPHA_SHIFT = {LOSS_ALPHA_SHIFT},")
    P(f"    parameter integer DRIVE_GAIN_SHIFT = {DRIVE_GAIN_SHIFT},")
    P(f"    parameter integer STEP_SHIFT = {STEP_SHIFT}")
    P(") (")
    P("    input  wire                    clk,")
    P("    input  wire                    rst,")
    P("    input  wire signed [WIDTH-1:0] loss,        // Q14.18 scalar loss of param_out")
    P("    output wire signed [WIDTH-1:0] param_out [0:N-1],  // dithered params: app evaluates THESE")
    P("    output reg  signed [WIDTH-1:0] param     [0:N-1],  // current learned values")
    P("    output reg                     updated           // 1-cycle pulse when param updated")
    P(");")
    P("")
    P(f"    localparam integer VREF_ACC_W = {VREF_ACC_W};")
    P(f"    localparam signed [WIDTH-1:0] STEP = {WIDTH}'sd{1 << STEP_SHIFT};")
    P(f"    localparam signed [WIDTH-1:0] DITHER_AMP = {hx(amp, WIDTH)}; // {AMP}")
    P("")
    for j in range(N):
        P(f"    localparam signed [WIDTH-1:0] K1_{j} = {hx(K[j][0], WIDTH)}; // {freqs[j]:.1f}Hz omega^2*dt")
        P(f"    localparam signed [WIDTH-1:0] K2_{j} = {hx(K[j][1], WIDTH)}; // {freqs[j]:.1f}Hz 2*damping*omega*dt")
        P(f"    localparam signed [WIDTH-1:0] K3_{j} = {hx(K[j][2], WIDTH)}; // {freqs[j]:.1f}Hz coupling*dt")
        P(f"    localparam [PHASE_BITS-1:0]   PINC_{j} = {PHASE_BITS}'d{pinc[j]}; // {freqs[j]:.1f}Hz DDS increment")
    P("")
    for nm, col in (("k1", 0), ("k2", 1), ("k3", 2)):
        P(f"    function signed [WIDTH-1:0] {nm}_of; input integer idx; begin")
        P(f"        case (idx)")
        for j in range(N):
            P(f"            {j}: {nm}_of = K{col + 1}_{j};")
        P(f"            default: {nm}_of = 0;")
        P(f"        endcase")
        P(f"    end endfunction")
    P("    function [PHASE_BITS-1:0] pinc_of; input integer idx; begin")
    P("        case (idx)")
    for j in range(N):
        P(f"            {j}: pinc_of = PINC_{j};")
    P("            default: pinc_of = 0;")
    P("        endcase")
    P("    end endfunction")
    P("")
    # sine LUT
    P("    reg signed [WIDTH-1:0] sine_lut [0:255];")
    P("    initial begin")
    for i in range(256):
        P(f"        sine_lut[{i}] = {hx(SINE_LUT[i], WIDTH)};")
    P("    end")
    P("")
    P("    reg signed [WIDTH-1:0]        x          [0:N-1];")
    P("    reg signed [WIDTH-1:0]        v          [0:N-1];")
    P("    reg signed [ENERGY_WIDTH-1:0] energy_ema [0:N-1];")
    P("    reg        [PHASE_BITS-1:0]   phase      [0:N-1];")
    P("    reg signed [VREF_ACC_W-1:0]   vref_acc   [0:N-1];")
    P("    reg signed [WIDTH-1:0]        loss_ema;")
    P("    reg                          started;")
    P("    integer                      win_ctr;")
    P("    integer                      gi;")
    P("")
    P("    // combinational: reference sample + dithered param for each channel")
    P("    wire signed [WIDTH-1:0]   dref      [0:N-1];")
    P("    wire signed [2*WIDTH-1:0] dith_full [0:N-1];   // wide: DITHER_AMP*dref overflows 32b near sine peaks")
    P("    genvar g;")
    P("    generate for (g = 0; g < N; g = g + 1) begin : chn")
    P("        assign dref[g]       = sine_lut[phase[g][PHASE_BITS-1 -: 8]];")
    P("        assign dith_full[g]  = $signed(DITHER_AMP) * $signed(dref[g]);")
    P("        assign param_out[g]  = param[g] + (dith_full[g] >>> FRAC);")
    P("    end endgenerate")
    P("")
    P("    always @(posedge clk) begin")
    P("        if (rst) begin")
    P("            for (gi = 0; gi < N; gi = gi + 1) begin")
    P("                x[gi] <= 0; v[gi] <= 0; energy_ema[gi] <= 0;")
    P("                phase[gi] <= 0; vref_acc[gi] <= 0; param[gi] <= 0;")
    P("            end")
    P("            loss_ema <= 0; started <= 1'b0; win_ctr <= 0; updated <= 1'b0;")
    P("        end else begin : step")
    P("            reg signed [WIDTH-1:0]   err, drive, k1x, k2v, k3d, v_new, x_new;")
    P("            reg signed [2*WIDTH-1:0] mul;")
    P("            reg signed [ENERGY_WIDTH-1:0] x2, e_new;")
    P("            reg signed [VREF_ACC_W-1:0] vr;")
    P("            reg do_update;")
    P("")
    P("            if (!started) begin loss_ema <= loss; started <= 1'b1; end")
    P("            err   = loss - loss_ema;")
    P("            loss_ema <= loss_ema + (err >>> LOSS_ALPHA_SHIFT);")
    P("            drive = err <<< DRIVE_GAIN_SHIFT;")
    P("            do_update = (win_ctr >= WINDOW - 1);")
    P("")
    P("            for (gi = 0; gi < N; gi = gi + 1) begin")
    P("                mul = k1_of(gi) * x[gi]; k1x = mul >>> FRAC;")
    P("                mul = k2_of(gi) * v[gi]; k2v = mul >>> FRAC;")
    P("                mul = k3_of(gi) * drive;  k3d = mul >>> FRAC;")
    P("                v_new = v[gi] - k1x - k2v + k3d;")
    P("                x_new = x[gi] + (v_new >>> DT_SHIFT);")
    P("                x2    = $signed(x_new) * $signed(x_new);")
    P("                e_new = energy_ema[gi] + ((x2 - energy_ema[gi]) >>> ALPHA_SHIFT);")
    P("")
    P("                vr = vref_acc[gi];")
    P("                if (win_ctr >= SETTLE) begin")
    P("                    mul = v_new * dref[gi];")
    P("                    vr  = vref_acc[gi] + (mul >>> FRAC);")
    P("                end")
    P("")
    P("                if (do_update) begin")
    P("                    if      (vr > 0) param[gi] <= param[gi] - STEP;")
    P("                    else if (vr < 0) param[gi] <= param[gi] + STEP;")
    P("                    x[gi] <= 0; v[gi] <= 0; energy_ema[gi] <= 0; vref_acc[gi] <= 0;")
    P("                end else begin")
    P("                    x[gi] <= x_new; v[gi] <= v_new; energy_ema[gi] <= e_new;")
    P("                    vref_acc[gi] <= vr;")
    P("                end")
    P("                phase[gi] <= phase[gi] + pinc_of(gi);")
    P("            end")
    P("")
    P("            if (do_update) begin win_ctr <= 0; updated <= 1'b1; end")
    P("            else            begin win_ctr <= win_ctr + 1; updated <= 1'b0; end")
    P("        end")
    P("    end")
    P("endmodule")
    return "\n".join(L) + "\n"


def gen_tb(freqs):
    N = len(freqs)
    tgt = [q(t) for t in TARGETS[:N]]
    L = []
    P = L.append
    P("// Auto-generated by gen_raf_learn.py -- DO NOT EDIT")
    P("// Closed-loop self-checking TB: L = sum_j (param_out_j - target_j)^2.")
    P("// Asserts every learned param_j converges to its target.")
    P("`timescale 1ns/1ps")
    P("module tb;")
    P(f"    localparam integer N = {N};")
    P(f"    localparam integer WIDTH = {WIDTH};")
    P(f"    localparam integer FRAC = {FRAC};")
    P(f"    localparam integer WINDOW = {WINDOW};")
    P(f"    localparam integer NWIN = {N_WINDOWS_TB};")
    P(f"    localparam signed [WIDTH-1:0] TOL = {hx(q(TOL), WIDTH)}; // {TOL}")
    P("")
    P("    reg clk = 0, rst = 1;")
    P("    reg  signed [WIDTH-1:0] loss;")
    P("    wire signed [WIDTH-1:0] param_out [0:N-1];")
    P("    wire signed [WIDTH-1:0] param     [0:N-1];")
    P("    wire                    updated;")
    P("")
    P("    spikeling_raf_learn dut (.clk(clk), .rst(rst), .loss(loss),")
    P("        .param_out(param_out), .param(param), .updated(updated));")
    P("    always #5 clk = ~clk;")
    P("")
    P("    reg signed [WIDTH-1:0] target [0:N-1];")
    for j in range(N):
        P(f"    initial target[{j}] = {hx(tgt[j], WIDTH)}; // {TARGETS[j]}")
    P("")
    P("    integer i, t, wins;")
    P("    reg signed [63:0] diff, sq, acc;")
    P("    initial begin")
    P("        @(negedge clk); rst = 0;")
    P("        wins = 0;")
    P("        for (t = 0; t < NWIN*WINDOW + 50; t = t + 1) begin")
    P("            acc = 0;")
    P("            for (i = 0; i < N; i = i + 1) begin")
    P("                diff = param_out[i] - target[i];")
    P("                sq   = (diff * diff) >>> FRAC;")
    P("                acc  = acc + sq;")
    P("            end")
    P("            loss = acc[WIDTH-1:0];")
    P("            @(negedge clk);")
    P("            if (updated) wins = wins + 1;")
    P("        end")
    P("        $display(\"[test] windows completed: %0d\", wins);")
    P("        begin : chk")
    P("            integer ok; reg signed [WIDTH-1:0] e;")
    P("            ok = 1;")
    P("            for (i = 0; i < N; i = i + 1) begin")
    P("                e = param[i] - target[i]; if (e < 0) e = -e;")
    P("                $display(\"  ch%0d  param=%0d  target=%0d  |err|=%0d  (TOL=%0d)\",")
    P("                         i, param[i], target[i], e, TOL);")
    P("                if (e > TOL) begin ok = 0; $display(\"[test] FAIL -- ch%0d did not converge\", i); end")
    P("            end")
    P("            if (ok) $display(\"\\n[test] PASS -- RAF on-chip learning rule converged all %0d channels within TOL\", N);")
    P("        end")
    P("        $finish;")
    P("    end")
    P("endmodule")
    return "\n".join(L) + "\n"


def main():
    freqs = [float(x) for x in sys.argv[1:]] or [311.0, 523.0, 881.0, 1483.0]
    open("spikeling_raf_learn.v", "w").write(gen_module(freqs))
    open("tb_raf_learn.v", "w").write(gen_tb(freqs))
    print(f"wrote spikeling_raf_learn.v + tb_raf_learn.v  ({len(freqs)} channels: {freqs})")
    print("build:  iverilog -g2012 -o raf_learn.vvp spikeling_raf_learn.v tb_raf_learn.v && vvp raf_learn.vvp")


if __name__ == "__main__":
    main()
